test("a mobile spin reveals the lesson action above the bottom navigation", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.getByRole("group", { name: "Category", exact: true }).getByRole("button", { name: "LLMs", exact: true }).click();
  await page.getByLabel("Level", { exact: true }).selectOption("Advanced");
  await page.getByRole("button", { name: "Start spinning", exact: true }).click();
  const action = page.getByRole("link", { name: "Start lesson", exact: true });
  await expect(action).toBeVisible();
  const topicName = await page.getByRole("region", { name: "Today's topic" }).getByRole("heading", { level: 2 }).innerText();
  await expect.poll(async () => {
    const button = await action.boundingBox();
    const navigation = await page.getByRole("navigation", { name: "Mobile", exact: true }).boundingBox();
    return Boolean(button && navigation && button.y + button.height <= navigation.y);
  }).toBe(true);
  await action.click();
  await expect(page.getByRole("heading", { name: topicName, exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Complete & next", exact: true })).toBeEnabled();
});
