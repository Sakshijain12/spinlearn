test("spins land in the center, persist, and respect the local re-spin limit", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Start spinning", exact: true })).toBeEnabled();
  await page.getByRole("group", { name: "Category", exact: true }).getByRole("button", { name: "LLMs", exact: true }).click();
  await page.getByLabel("Level", { exact: true }).selectOption("Advanced");
  await expect(page.getByText("3 complete lessons match your filters.", { exact: true })).toBeVisible();
  const firstResponse = page.waitForResponse((response) => response.url().endsWith("/api/v1/spin") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Start spinning", exact: true }).click();
  const firstResult = spinResponseSchema.parse(await (await firstResponse).json());
  expect(new Set(firstResult.reel.options).size).toBeGreaterThan(1);
  await expect(page.getByRole("region", { name: "Today's topic" }).getByRole("heading", { name: firstResult.spin.topic.name, exact: true })).toBeVisible();
  const landing = await page.locator(".reel-row").nth(40).boundingBox();
  const band = await page.locator(".reel-band").boundingBox();
  expect(landing).not.toBeNull();
  expect(band).not.toBeNull();
  expect(Math.abs(landing!.y + landing!.height / 2 - band!.y - band!.height / 2)).toBeLessThan(1);
  await page.getByRole("button", { name: "Save for later", exact: true }).click();
  await expect(page.getByRole("button", { name: "Saved for later", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.reload();
  await expect(page.getByRole("button", { name: "Saved for later", exact: true })).toBeVisible();
  await page.getByRole("group", { name: "Category", exact: true }).getByRole("button", { name: "LLMs", exact: true }).click();
  await page.getByLabel("Level", { exact: true }).selectOption("Advanced");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  const secondResponse = page.waitForResponse((response) => response.url().endsWith("/api/v1/spin") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Spin again", exact: true }).click();
  const secondResult = spinResponseSchema.parse(await (await secondResponse).json());
  expect(secondResult.spin.topic.slug).not.toBe(firstResult.spin.topic.slug);
  await expect(page.locator(".reel-strip")).toHaveCSS("transition-duration", "3.4s");
  await expect(page.getByRole("button", { name: "Come back tomorrow", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Come back tomorrow", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "You've used today's re-spin" })).toBeVisible();
  await page.getByRole("navigation", { name: "Primary", exact: true }).getByRole("link", { name: "Library", exact: true }).click();
  await page.getByRole("button", { name: "Saved (1)", exact: true }).click();
  await expect(page.locator("article")).toHaveCount(1);
  await expect(page.locator("article").getByRole("link", { name: firstResult.spin.topic.name, exact: true })).toBeVisible();
});

